"""
Produce the change list for the highlighted resubmission PDF.

The list is generated by diffing the revised manuscript against the version as
submitted, not written from memory, so nothing that changed can be omitted by
oversight. Each changed region is attributed to the section containing it and
classified as NEW (text absent from the submitted version), REVISED (text that
replaced something), or REMOVED.

The baseline is access.tex, which is the submitted content. Purely cosmetic
differences introduced during the IEEE conversion -- float placement, figure
widths, running heads -- are filtered out so the list reflects substantive
changes only.
"""
import io
import os
import re
import difflib

TEXDIR = os.path.join("E:" + os.sep, "Dream_Analysis")
OLD = os.path.join(TEXDIR, "access.tex")
NEW = os.path.join(TEXDIR, "accesstemp.tex")
OUT = os.path.join(TEXDIR, "CHANGE-LIST_Access-2026-38077.txt")

# differences that are formatting only and need no highlighting
COSMETIC = re.compile(
    r"^\s*(\\begin\{(figure|table)\*?\}|\\end\{(figure|table)\*?\}|"
    r"\\centering|\\small|\\normalsize|\\footnotesize|\\toprule|\\midrule|"
    r"\\botrule|\\addlinespace.*|\\includegraphics.*|\\markboth|"
    r"\\vspace.*|\\label\{.*|\\usepackage.*|\\cmidrule.*)\s*$")

lines_out = []


def log(m=""):
    print(m, flush=True)
    lines_out.append(str(m))


def section_map(lines):
    """line index -> (section, subsection) as they will be numbered."""
    ROM = ["", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X",
           "XI", "XII"]
    out, sec, sub = {}, 0, 0
    cs, cu = "(front matter)", ""
    for i, ln in enumerate(lines):
        m = re.match(r"\\section\*?\{([^}]*)\}", ln)
        if m:
            sec += 1
            sub = 0
            cs = f"{ROM[sec] if sec < len(ROM) else sec}. {m.group(1)}"
            cu = ""
        m = re.match(r"\\subsection\*?\{([^}]*)\}", ln)
        if m:
            sub += 1
            nm = re.sub(r"\\label\{[^}]*\}", "", m.group(1))
            cu = (f"{ROM[sec] if sec < len(ROM) else sec}-"
                  f"{chr(ord('A') + sub - 1)}. {nm}")
        out[i] = (cs, cu)
    return out


def substantive(block):
    keep = [l for l in block
            if l.strip() and not COSMETIC.match(l) and len(l.split()) > 3]
    return keep


def main():
    old = io.open(OLD, encoding="utf-8").read().split("\n")
    new = io.open(NEW, encoding="utf-8").read().split("\n")
    smap = section_map(new)

    sm = difflib.SequenceMatcher(None, old, new, autojunk=False)

    log("=" * 78)
    log("CHANGE LIST FOR THE HIGHLIGHTED PDF")
    log("Manuscript Access-2026-38077")
    log("=" * 78)
    log("")
    log("Generated by diffing the revised manuscript against the version as")
    log("submitted. NEW = text not present before; REVISED = text that")
    log("replaced earlier text. Formatting-only differences are excluded.")
    log("")

    groups = {}
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            continue
        added = substantive(new[j1:j2])
        removed = substantive(old[i1:i2])
        if not added and not removed:
            continue
        # A single diff region can span a section boundary -- a new subsection
        # inserted directly after another one merges into one opcode. Split the
        # region so each subsection is credited with its own text.
        pieces = {}
        for j in range(j1, max(j2, j1 + 1)):
            sec, sub = smap.get(j, ("(front matter)", ""))
            pieces.setdefault(sub or sec, []).append(j)
        for key, idx in pieces.items():
            part = substantive([new[j] for j in idx if j < len(new)])
            if not part and not (removed and key == list(pieces)[0]):
                continue
            groups.setdefault(key, {"new": 0, "rev": 0, "lines": [],
                                    "words": 0})
            g = groups[key]
            if part and not removed:
                g["new"] += 1
            else:
                g["rev"] += 1
            g["words"] += sum(len(l.split()) for l in part)
            if part:
                g["lines"].append((idx[0] + 1, idx[-1] + 1, part[0][:88]))

    order = []
    seen = set()
    for i in range(len(new)):
        k = smap.get(i, ("", ""))[1] or smap.get(i, ("", ""))[0]
        if k and k not in seen:
            seen.add(k)
            order.append(k)

    total_w = 0
    for k in order:
        if k not in groups:
            continue
        g = groups[k]
        total_w += g["words"]
        kind = ("ENTIRELY NEW" if g["rev"] == 0 else
                "REVISED" if g["new"] == 0 else "NEW + REVISED")
        log("-" * 78)
        log(f"{k}")
        log(f"   {kind}  |  {g['new'] + g['rev']} changed region(s)  |  "
            f"~{g['words']} words added")
        for a, b, txt in g["lines"][:6]:
            log(f"      lines {a}-{b}: {txt}...")
        if len(g["lines"]) > 6:
            log(f"      ... and {len(g['lines']) - 6} further region(s)")
        log("")

    log("=" * 78)
    log("SUMMARY")
    log("=" * 78)
    log(f"sections touched : {len(groups)}")
    log(f"words added      : ~{total_w}")
    log(f"manuscript grew  : {sum(len(l.split()) for l in old)} -> "
        f"{sum(len(l.split()) for l in new)} words")
    log("")
    log("Sections that are new in their entirety and can be highlighted whole:")
    for k in order:
        if k in groups and groups[k]["rev"] == 0 and groups[k]["words"] > 120:
            log(f"   {k}")

    io.open(OUT, "w", encoding="utf-8").write("\n".join(lines_out))
    log("")
    log(f"Written to {OUT}")


if __name__ == "__main__":
    main()
