"""
Cohort manifests, fold assignments and window-level predictions for the
supplementary material (Reviewer 1, comment 12).

  manifest_deed.csv          every analysed DEED window: row index, participant,
                             recording, night, report category, valence label
  manifest_tononi.csv        every analysed Tononi window
  manifest_sleepedf.csv      participant and window counts per stage (the
                             window table itself is 183,775 rows and is
                             regenerated by the feature script)
  folds_deed.csv             for each window, its test fold under each of the
                             ten fold assignments and each partition of
                             Table 4(a) (window-shuffled, recording-grouped,
                             participant-separated), exactly as constructed by
                             51_protocol_table.py and 65_config_table.py
  predictions_deed.parquet   out-of-fold predictions of the headline random
                             forest and of the balanced logistic regression,
                             participant-separated, all ten fold assignments,
                             produced with 65's evaluate() settings (BLAS pinned)

Every file is keyed by the same row index, so predictions can be joined to
participants, recordings and labels, and any participant-level summary in the
paper can be recomputed.
"""
import importlib.util
import os

import numpy as np
import pandas as pd
from sklearn.model_selection import StratifiedGroupKFold, StratifiedKFold
from threadpoolctl import threadpool_limits

HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location(
    "t5", os.path.join(HERE, "65_config_table.py"))
t5 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(t5)
OUT = t5.OUT
SUP = os.path.join(OUT, "supplement")
os.makedirs(SUP, exist_ok=True)


def deed():
    d = pd.read_parquet(os.path.join(OUT, "features_epoch_filtered.parquet"))
    fc = [c for c in d.columns if c not in t5.META]
    d = d.replace([np.inf, -np.inf], np.nan).dropna(subset=fc)
    d = d[d.E.isin(t5.VALENCE)].reset_index(drop=True)
    return d, fc


def main():
    d, fc = deed()
    X, y = d[fc].to_numpy(float), d.E.map(t5.VALENCE).to_numpy()
    subj, rec = d.subject.to_numpy(), d.segment_id.to_numpy()
    # identical arrays to 65's load()
    X5, y5, s5, r5 = t5.load()
    assert (y5 == y).all() and (s5 == subj).all() and (r5 == rec).all()
    man = pd.DataFrame(dict(row=np.arange(len(d)), participant=subj,
                            recording=rec, night=d.oid.to_numpy(),
                            report=d.E.to_numpy(), valence=y))
    man.to_csv(os.path.join(SUP, "manifest_deed.csv"), index=False)

    folds = man[["row"]].copy()
    for seed in t5.SEEDS:
        for name, grp in (("window", None), ("recording", rec),
                          ("participant", subj)):
            f = np.full(len(y), -1)
            if grp is None:
                sp = StratifiedKFold(5, shuffle=True,
                                     random_state=seed).split(X, y)
            else:
                sp = StratifiedGroupKFold(5, shuffle=True,
                                          random_state=seed).split(X, y, grp)
            for k, (_, te) in enumerate(sp):
                f[te] = k
            assert (f >= 0).all()
            folds[f"{name}_{seed}"] = f
    folds.to_csv(os.path.join(SUP, "folds_deed.csv"), index=False)

    rows = []
    for cfg in ("RF, unweighted (headline)", "LogReg, scaled, balanced"):
        kind, scale, weight = t5.CONFIGS[cfg]
        for seed in t5.SEEDS:
            sp = StratifiedGroupKFold(5, shuffle=True,
                                      random_state=seed).split(X, y, subj)
            pred = np.empty(len(y), dtype=object)
            with threadpool_limits(t5.BLAS_THREADS, user_api="blas"):
                for tr, te in sp:
                    m = t5.build(kind, scale, weight, seed).fit(X[tr], y[tr])
                    pred[te] = m.predict(X[te])
            rows.append(pd.DataFrame(dict(row=np.arange(len(y)), config=cfg,
                                          fold_seed=seed, pred=pred)))
            print(f"{cfg} seed {seed} done", flush=True)
    p = pd.concat(rows, ignore_index=True)
    p.to_parquet(os.path.join(SUP, "predictions_deed.parquet"))
    # check against Table 5: pooled balanced accuracy per assignment
    from sklearn.metrics import balanced_accuracy_score
    chk = (p.merge(man[["row", "valence"]], on="row")
           .groupby(["config", "fold_seed"])
           .apply(lambda g: balanced_accuracy_score(g.valence, g.pred)))
    print(chk.groupby("config").mean().round(4))

    t = pd.read_parquet(os.path.join(OUT, "tononi_features.parquet"))
    tfc = [c for c in t.columns if c.startswith("ch")]
    t = t.replace([np.inf, -np.inf], np.nan).dropna(subset=tfc)
    pd.DataFrame(dict(row=np.arange(len(t)),
                      participant=t.subject.astype(str).to_numpy(),
                      recording=t.recording.astype(str).to_numpy(),
                      label=t.dreaming.astype(str).to_numpy())).to_csv(
        os.path.join(SUP, "manifest_tononi.csv"), index=False)

    s = pd.read_parquet(os.path.join(OUT, "sleepedf_expanded_features.parquet"))
    sfc = [c for c in s.columns if c.startswith("ch")]
    s = s.replace([np.inf, -np.inf], np.nan).dropna(subset=sfc)
    (s.groupby(["subject", "stage"]).size().unstack(fill_value=0)
     .to_csv(os.path.join(SUP, "manifest_sleepedf.csv")))
    print("manifests, folds and predictions written to", SUP)


if __name__ == "__main__":
    main()
